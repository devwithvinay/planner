create table if not exists public.daily_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  day_number int not null check (day_number between 1 and 90),
  completed_tasks text[] not null default '{}',
  notes text not null default '',
  updated_at timestamptz not null default now(),
  unique (user_id, day_number)
);

create table if not exists public.weekly_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  week_number int not null check (week_number between 1 and 13),
  wins text not null default '',
  challenges text not null default '',
  next_week text not null default '',
  applications_count int not null default 0 check (applications_count >= 0),
  updated_at timestamptz not null default now(),
  unique (user_id, week_number)
);

alter table public.daily_progress enable row level security;
alter table public.weekly_reviews enable row level security;

create policy "Users can read own daily progress"
on public.daily_progress for select using (auth.uid() = user_id);
create policy "Users can insert own daily progress"
on public.daily_progress for insert with check (auth.uid() = user_id);
create policy "Users can update own daily progress"
on public.daily_progress for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can delete own daily progress"
on public.daily_progress for delete using (auth.uid() = user_id);

create policy "Users can read own weekly reviews"
on public.weekly_reviews for select using (auth.uid() = user_id);
create policy "Users can insert own weekly reviews"
on public.weekly_reviews for insert with check (auth.uid() = user_id);
create policy "Users can update own weekly reviews"
on public.weekly_reviews for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can delete own weekly reviews"
on public.weekly_reviews for delete using (auth.uid() = user_id);